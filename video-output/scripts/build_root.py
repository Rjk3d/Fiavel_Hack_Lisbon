"""Writes index.html (scene hosts, voice, sound effects), compositions/captions.html and
assets/cues.js from timing.json, so picture, voice and captions always share one clock.

    python3 scripts/build_root.py
"""

import html
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
timing = json.loads((ROOT / "timing.json").read_text())
scenes = {s["id"]: s for s in timing["scenes"]}
TOTAL = timing["total"]


def cue(scene: str, text: str) -> float:
    """Absolute time at which the voice starts the caption group beginning with `text`."""
    s = scenes[scene]
    g = next(g for g in s["groups"] if g["text"].startswith(text))
    return round(s["start"] + g["start"], 3)


def at(scene: str, local: float) -> float:
    return round(scenes[scene]["start"] + local, 3)


# Sound effects: each has a cause on screen (sound.md §4). Times are when the sound should hit;
# `lead` is how far into the file its peak sits (measured with `hyperframes audio`).
SFX = [
    ("whoosh-cinematic", at("s1-problem", scenes["s1-problem"]["duration"] - 1.2), 0.35, 0.0),  # the deposit line becomes the reveal
    ("sparkle", at("s2-reveal", 0.55), 0.3, 0.0),  # the mark lands
    ("whoosh-short", at("s2-reveal", scenes["s2-reveal"]["duration"] * 0 + 4.35), 0.3, 0.0),  # field carried into the app's card
    ("whoosh", cue("s3-sides", "what was agreed") - 0.25, 0.25, 0.0),  # two sides collapse to one
    ("whoosh-short", at("s4-stellar", 0.35), 0.3, 0.0),  # the app lifts, the contract appears
    ("pop", cue("s4-stellar", "its transaction") + 0.1, 0.3, 0.0),  # transaction card lands
    ("click-soft", at("s5-agents", 0.45), 0.4, 0.0),  # question sent
    ("pop", cue("s5-agents", "they do not replace") + 0.2, 0.28, 0.0),  # refusal appears
    ("click-soft", cue("s6-blend", "with explicit consent") + 0.35, 0.4, 0.0),  # the consent button
    ("pop", cue("s7-reputation", "Fiável is also exploring") + 0.4, 0.25, 0.0),  # demo label
    ("whoosh-short", cue("s8-montage", "Stellar payments") - 0.1, 0.22, 0.0),
    ("whoosh", cue("s8-montage", "and a transparent") - 0.1, 0.22, 0.0),
    ("riser", at("s9-end", 0.95) - 3.0, 0.22, 7.0),  # last 3 s of the riser, into the mark
    ("impact-bass-1", at("s9-end", 0.95), 0.35, 0.0),  # the mark lands
]

# Scene timing for the compositions: local cue times by caption text.
cues = {
    sid: {"duration": s["duration"], "voice": s["voice_start"], "groups": [[g["text"], g["start"], g["end"]] for g in s["groups"]]}
    for sid, s in scenes.items()
}
(ROOT / "assets" / "cues.js").write_text(
    "// Generated by scripts/build_root.py from timing.json: local cue times per scene.\n"
    f"window.FILM_CUES = {json.dumps(cues, ensure_ascii=False)};\n"
    "window.filmCue = (scene, text, edge = 0) => {\n"
    "  const g = window.FILM_CUES[scene].groups.find((x) => x[0].startsWith(text));\n"
    "  if (!g) throw new Error(`no cue \"${text}\" in ${scene}`);\n"
    "  return g[1 + edge];\n"
    "};\n",
    encoding="utf-8",
)

hosts, audio = [], []
for i, (sid, s) in enumerate(scenes.items()):
    hosts.append(
        f'      <div id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html" '
        f'data-start="{s["start"]}" data-duration="{s["duration"]}" data-track-index="1" data-track-kind="graphics" '
        f'data-width="1920" data-height="1080" style="z-index:{i + 1}"></div>'
    )
    audio.append(
        f'      <audio id="voice-{sid}" class="clip" src="{s["voice"]}" data-start="{round(s["start"] + s["voice_start"], 3)}" '
        f'data-duration="{s["voice_length"]}" data-track-index="3" data-volume="1"></audio>'
    )
def length(path: Path) -> float:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)], capture_output=True, text=True, check=True)
    return float(out.stdout)


for n, (name, t, vol, media_start) in enumerate(SFX):
    attrs = f'data-media-start="{media_start}" ' if media_start else ""
    dur = round(min(length(ROOT / "assets" / "sfx" / f"{name}.mp3") - media_start, TOTAL - t), 3)
    audio.append(
        f'      <audio id="sfx-{n:02d}-{name}" class="clip" src="assets/sfx/{name}.mp3" data-start="{t}" data-duration="{dur}" {attrs}'
        f'data-track-index="{4 + n % 2}" data-volume="{vol}"></audio>'
    )

index = f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>Fiável — HackMeridian film</title>
    <script src="assets/vendor/gsap.min.js"></script>
    <script src="assets/cues.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1920px; height: 1080px; overflow: hidden; background: #faf9fd; }}
      #root {{ position: relative; width: 1920px; height: 1080px; overflow: hidden; background: #faf9fd; font-family: Inter, sans-serif; }}
    </style>
  </head>
  <body>
    <!-- Generated by scripts/build_root.py from timing.json. Edit the scenes in compositions/. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{TOTAL}" data-width="1920" data-height="1080">
{chr(10).join(hosts)}
      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" data-start="0" data-duration="{TOTAL}" data-track-index="2" data-track-kind="captions" data-width="1920" data-height="1080" style="z-index:50"></div>
{chr(10).join(audio)}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
(ROOT / "index.html").write_text(index, encoding="utf-8")

groups = []
for s in scenes.values():
    for g in s["groups"]:
        groups.append((round(s["start"] + g["start"] - 0.08, 3), round(s["start"] + g["end"] + 0.12, 3), g["text"]))
# One group at a time: a group closes no later than the next one opens.
caps, script = [], []
for i, (start, end, text) in enumerate(groups):
    if i + 1 < len(groups):
        end = min(end, groups[i + 1][0])
    start = max(start, 0.15)
    dur = round(end - start, 3)
    caps.append(f'    <div id="cap-{i:02d}" class="cap clip" data-start="{start}" data-duration="{dur}"><span>{html.escape(text)}</span></div>')
    script.append(f"    show('#cap-{i:02d} span', {start}, {round(start + dur, 3)});")

captions = f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; pointer-events: none; }}
    .cap {{ position: absolute; left: 0; right: 0; bottom: 104px; text-align: center; overflow: visible; }}
    .cap span {{
      display: inline-block; max-width: 1500px; padding: 10px 26px 12px; border-radius: 18px;
      background: rgba(255, 255, 255, 0.9); box-shadow: 0 10px 30px -14px rgba(23, 19, 41, 0.35);
      font-family: Inter, sans-serif; font-weight: 700; font-size: 44px; line-height: 1.25;
      letter-spacing: -0.01em; color: #171329; opacity: 0;
    }}
  </style>
  <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
{chr(10).join(caps)}
  </div>
  <script>
    const tl = gsap.timeline({{ paused: true }});
    // Each group fades in with its first word and is killed after its last one (captions.md).
    function show(sel, start, end) {{
      tl.fromTo(sel, {{ opacity: 0, filter: "blur(4px)" }}, {{ opacity: 1, filter: "blur(0px)", duration: 0.14, ease: "power2.out" }}, start);
      tl.to(sel, {{ opacity: 0, duration: 0.1, ease: "power2.in" }}, Math.max(start + 0.15, end - 0.1));
      tl.set(sel, {{ opacity: 0 }}, end);
    }}
{chr(10).join(script)}
    window.__timelines["captions"] = tl;
  </script>
</template>
"""
(ROOT / "compositions").mkdir(exist_ok=True)
(ROOT / "compositions" / "captions.html").write_text(captions, encoding="utf-8")
print(f"index.html: {len(scenes)} scenes, {len(SFX)} sound effects, {TOTAL}s · captions: {len(groups)} groups")
