import { test, expect } from '@playwright/test'

async function openDemo(page) {
  await page.goto('/app/reviews')
  await expect(page.getByRole('heading',{name:'Good renting leaves a good story.'})).toBeVisible()
  await page.getByRole('button',{name:'Explore review demo'}).click()
  await expect(page.getByRole('heading',{name:'Your review invitations'})).toBeVisible()
}
async function draft(page, text, rating = 4) {
  await page.getByRole('button',{name:'Write review',exact:true}).click()
  await expect(page.getByRole('button',{name:'Continue',exact:true})).toBeDisabled()
  const fields = page.locator('fieldset')
  for (let i=0;i<await fields.count();i++) await fields.nth(i).getByRole('radio').nth(rating-1).check()
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.getByRole('textbox',{name:/Your experience, in your own words/}).fill(text)
  await page.getByRole('button',{name:'Preview review'}).click()
  await expect(page.locator('.review-form')).toContainText(text)
}
async function submit(page, text, rating = 4) {
  await draft(page,text,rating)
  await page.getByRole('button',{name:'Submit demo review'}).click()
  await expect(page.getByRole('heading',{name:'Review submitted',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Close',exact:true}).click()
}

