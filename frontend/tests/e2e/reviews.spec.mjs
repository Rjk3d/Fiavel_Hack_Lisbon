test('rapid clicks send one submission; failed persistence is never presented as success', async ({page}) => {
  await openDemo(page)
  await draft(page,'Repairs were handled promptly.')
  let attempts=0
  await page.route('**/api/reviews',async route=>{
    if(route.request().method()==='POST') { attempts++; await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Storage is unavailable. Please retry.'})}) }
    else await route.continue()
  })
  await page.getByRole('button',{name:'Submit demo review'}).evaluate(button=>{button.click();button.click()})
  await expect(page.getByRole('alert')).toContainText('Storage is unavailable')
  await expect(page.getByRole('heading',{name:'Review submitted',exact:true})).toHaveCount(0)
  expect(attempts).toBe(1)
  await page.unroute('**/api/reviews')
  await page.getByRole('button',{name:'Submit demo review'}).click()
  await expect(page.getByRole('heading',{name:'Review submitted',exact:true})).toBeVisible()
})

test('backend outages and malformed proxy responses show recoverable errors', async ({page}) => {
  await page.route('**/api/reviews',route=>route.abort('failed'))
  await page.goto('/app/reviews')
  await expect(page.getByRole('alert')).toContainText('Cannot reach the review server')
  await expect(page.getByRole('button',{name:'Explore review demo'})).toBeEnabled()
  await page.unroute('**/api/reviews')
  await page.route('**/api/reviews/session',route=>route.fulfill({status:502,contentType:'text/html',body:'Bad gateway'}))
  await page.getByRole('button',{name:'Explore review demo'}).click()
  await expect(page.getByRole('alert')).toContainText('invalid response')
  await page.unroute('**/api/reviews/session')
  await page.getByRole('button',{name:'Explore review demo'}).click()
  await expect(page.getByRole('heading',{name:'Your review invitations'})).toBeVisible()
})

